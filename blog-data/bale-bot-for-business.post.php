برای خیلی از کسب‌وکارهای ایرانی، مشتری‌ها همان‌جایی هستند که هر روز پیام می‌دهند و جواب می‌گیرند. اگر بخش بزرگی از مخاطبان شما از **بله** استفاده می‌کنند، ساختن یک ربات در همان پیام‌رسان، مسیر ارتباط را بسیار کوتاه می‌کند: مشتری نیاز به نصب برنامهٔ تازه یا یاد گرفتن چیز جدیدی ندارد.

## ربات بله چه کارهایی می‌تواند بکند؟

ربات‌ها در بله با همان منطق آشنای پیام‌رسان‌ها کار می‌کنند: کاربر دستور می‌فرستد یا دکمه‌ای را می‌زند و ربات پاسخ می‌دهد. کاربردهای رایج:

- **ثبت سفارش و فروش:** نمایش محصول، انتخاب مشخصات، دریافت آدرس و پیگیری وضعیت. نمونه‌ای از این کار را در [بازو فروش‌یار](/portfolio/froshyar/) ببینید.
- **پشتیبانی و پاسخ‌گویی:** جواب خودکار به سوال‌های پرتکرار و ارجاع موارد پیچیده به شما.
- **اعلان به مدیر:** هر وقت درخواست یا سفارشی ثبت شد، پیام آنی به صاحب کسب‌وکار برسد.
- **آموزش و سرگرمی:** آزمون، مسابقه یا تمرین روزانه، مثل [ربات آموزش لغت](/portfolio/yaren/).
- **فرم‌ها و ثبت‌نام:** جمع‌آوری اطلاعات کاربران بدون صفحهٔ جداگانه.

درباره پرداخت درون پیام‌رسان هم پلتفرم امکاناتی ارائه می‌کند، اما شرایط فعال‌سازی آن را حتماً از مستندات رسمی بله بررسی کنید، چون ممکن است در طول زمان تغییر کند.

## بله یا تلگرام؟

هیچ پاسخ جهانی وجود ندارد. سوال درست این است: **مخاطبان من کجا هستند؟** اگر بیشتر مشتریان شما در تلگرام فعال‌اند، همان‌جا شروع کنید. اگر مخاطب شما عمدتاً ایرانی است و از بله استفاده می‌کند یا می‌خواهید امکانی مثل پیام‌رسان داخلی را هم پوشش دهید، ربات بله منطقی است. بسیاری از پروژه‌ها در عمل هر دو را می‌خواهند. برای تصمیم‌گیری دقیق‌تر، مقالهٔ [ربات تلگرام یا وبسایت؟](/blog/telegram-bot-or-website/) هم می‌تواند کمک کند.

## چطور شروع کنیم؟

1. **هدف را مشخص کنید.** ربات قرار است چه مشکلی را حل کند؟ یک جمله بنویسید.
2. **ربات را بسازید.** از ربات رسمی ساخت بازو در بله یک ربات جدید بسازید و توکن آن را بگیرید.
3. **مسیر کاربر را طراحی کنید.** از «سلام» تا «انجام کار» چند مرحله است؟ هر مرحلهٔ اضافه، کاربران بیشتری را از دست می‌دهد.
4. **منطق و دیتابیس را بنویسید.** وضعیت هر کاربر و سفارش‌ها باید جایی ذخیره شود.
5. **وب‌هوک را فعال کنید.** برای اینکه ربات پیام‌ها را فوری دریافت کند، سرور شما باید روی HTTPS در دسترس باشد.
6. **تست کنید.** حالت‌های غیرمعمول مثل لغو وسط کار، متن اشتباه یا ارسال عکس به‌جای متن را امتحان کنید.

## چند نکتهٔ امنیتی

توکن ربات را مثل رمز عبور نگه دارید و آن را داخل فایلی که به‌صورت عمومی قابل دانلود است قرار ندهید. اگر روزی فاش شد، از همان ربات رسمی توکن را بازنشانی کنید. اطلاعات مشتریان را هم فقط در جایی ذخیره کنید که از بیرون قابل دسترسی نیست.

## هزینه و زمان

مثل هر پروژهٔ نرم‌افزاری، هزینه به قابلیت‌ها، اتصال‌ها و پنل مدیریت بستگی دارد. جزئیات را در [هزینه ساخت ربات تلگرام](/blog/telegram-bot-cost/) توضیح داده‌ایم و بیشتر آن برای ربات بله هم صدق می‌کند. اگر ایده‌ای دارید، بنویسید تا پس از بررسی، مسیر و برآورد تقریبی را اعلام کنم.
