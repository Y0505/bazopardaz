تا همین چند وقت پیش، «ربات تلگرام» یعنی گفتگوی متنی با چند دکمه. مینی‌اپ‌ها این تجربه را تغییر داده‌اند: می‌توانید یک **صفحهٔ وب کامل با طراحی دلخواه** را داخل خود تلگرام باز کنید، بدون اینکه کاربر برنامه‌ای نصب کند یا به مرورگر برود.

## مینی‌اپ دقیقاً چیست؟

مینی‌اپ تلگرام یک برنامهٔ وب (با HTML، CSS و جاوااسکریپت) است که داخل پنجرهٔ تلگرام اجرا می‌شود. کاربر آن را از طریق یک ربات باز می‌کند، مثلاً با دکمهٔ منو یا یک دکمهٔ داخل پیام. چون این پنجره یک صفحهٔ وب است، هر چیزی که در وب ممکن است، مثل لیست محصول با تصویر، سبد خرید، تقویم رزرو، نمودار یا بازی، در آن هم ممکن است.

## فرقش با ربات معمولی چیست؟

ربات معمولی مثل یک گفتگوی خط‌به‌خط است. مینی‌اپ مثل یک اپلیکیشن کوچک است. تفاوت را بیشتر وقتی حس می‌کنید که کاربر باید چیزی را **ببیند یا انتخاب کند**:

- در ربات، انتخاب از بین ۳۰ محصول یعنی کلی صفحه‌ورق‌زدن؛ در مینی‌اپ، یک ویترین ساده با جست‌وجو.
- در ربات، پر کردن یک فرم بلند یعنی ده پیام پشت‌سرهم؛ در مینی‌اپ، یک فرم تمیز با اعتبارسنجی لحظه‌ای.
- در ربات، نمایش تقویم یا نقشه دشوار است؛ در مینی‌اپ، همان ابزارهای معمول وب را به کار می‌برید.

## کاربردهای واقعی

1. **فروشگاه:** ویترین محصولات، فیلتر، سبد خرید و پیگیری سفارش.
2. **رزرو و نوبت‌دهی:** انتخاب روز و ساعت روی تقویم، به‌جای رد و بدل کردن چند پیام.
3. **فرم‌ها و ثبت‌نام:** پرسش‌نامه، ثبت‌نام رویداد یا درخواست خدمات.
4. **بازی و سرگرمی:** بازی‌های سبک که با دوستان از طریق تلگرام به اشتراک گذاشته می‌شوند. نمونهٔ [بازی شطرنج](/portfolio/chess/) در نمونه‌کارهای ما از همین نوع است.
5. **داشبورد و گزارش:** نمایش آمار شخصی یا خلاصهٔ حساب برای کاربر.

## مزایا

- تجربهٔ کاربری شبیه اپلیکیشن، بدون نیاز به نصب.
- ورود ساده، چون تلگرام هویت کاربر را در اختیار برنامه می‌گذارد.
- یک بار توسعه، اجرا برای همهٔ دستگاه‌هایی که تلگرام دارند.
- امکان استفاده از همان فناوری‌های وب که تیم شما شاید همین حالا می‌شناسد.

## محدودیت‌ها و نکات مهم

مینی‌اپ جادو نیست و باید چند نکته را رعایت کرد:

- باید روی HTTPS میزبانی شود و سرعت بالا مهم است، چون کاربر منتظر لود طولانی نمی‌ماند.
- داده‌هایی که از سمت کاربر می‌رسد را باید **در سرور اعتبارسنجی** کرد؛ هرگز نباید فقط به سمت مرورگر اعتماد کرد.
- طراحی باید موبایل‌محور باشد، چون بیشتر کاربران از گوشی استفاده می‌کنند.
- به پلتفرم وابسته‌اید و اگر قوانین یا امکانات آن تغییر کند، باید برنامه را به‌روز کنید.

## کی لازم نیست؟

اگر کار شما با چند دکمه و پیام حل می‌شود، مثل پاسخ به سوال‌های پرتکرار یا ارسال اعلان، یک ربات ساده کافی است و هزینهٔ کمتری دارد. مینی‌اپ وقتی ارزش می‌سازد که کاربر باید چیزی را ببیند، مقایسه کند یا با یک رابط تصویری تعامل داشته باشد. اگر هنوز تردید دارید، با [مقایسهٔ ربات و وبسایت](/blog/telegram-bot-or-website/) شروع کنید و بعد سراغ جزئیات بروید.
